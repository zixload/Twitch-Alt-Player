restes = []
for i, texte in enumerate(ordre):
    if i == 178:
        continue
    if i in SUB:
        neuf = texte
        # Du plus long au plus court : un motif generique ne doit pas entamer un motif
        # specifique qui le contient, sinon il laisse derriere lui un prefixe cyrillique.
        for de, vers in sorted(SUB[i], key=lambda p: -len(p[0])):
            neuf = neuf.replace(de, vers)
        if i == 67:
            # Les plages de lignes de la table des matieres sont perimees depuis longtemps.
            neuf = re.sub(r'\.*\(lines \d+-\d+\)', '', neuf)
        if cyr.search(neuf):
            restes.append((i, [m for m in cyr.findall(neuf)][:3]))
        out[str(i)] = neuf
    elif i in T:
        out[str(i)] = T[i]
    else:
        restes.append((i, 'aucune traduction'))

